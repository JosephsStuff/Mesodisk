        private void ShowResult(JobResult r)
        {
            DiskInfo disk = r.After ?? r.Disk;
            CdiDisk cdi = r.Cdi;

            // Health
            string status = r.HealthStatus;
            int? percent = r.HealthPercent;
            healthCard.SetStatus(status.ToUpperInvariant(), Palette.ForHealth(status), percent.HasValue ? percent.Value.ToString(CultureInfo.InvariantCulture) + " %" : "");

            List<string[]> health = new List<string[]>();
            if (cdi != null)
            {
                health.Add(new string[] { "Temperature", cdi.Field("Temperature") });
                health.Add(new string[] { "Power on hours", cdi.Field("Power On Hours") });
                health.Add(new string[] { "Power on count", cdi.Field("Power On Count") });
                AddIfPresent(health, "Host writes", cdi.Field("Host Writes"));
                AddIfPresent(health, "Host reads", cdi.Field("Host Reads"));
                AddIfPresent(health, "NAND writes", cdi.Field("NAND Writes"));
                AddIfPresent(health, "Wear level count", cdi.Field("Wear Level Count"));
                health.Add(new string[] { "Source", "CrystalDiskInfo " + CdiRunner.Version });
            }
            else
            {
                HealthReport fallback = r.Fallback;
                health.Add(new string[] { "Temperature", fallback != null && fallback.TemperatureC.HasValue ? fallback.TemperatureC.Value.ToString(CultureInfo.InvariantCulture) + " C" : "" });
                health.Add(new string[] { "Power on hours", fallback != null && fallback.PowerOnHours.HasValue ? fallback.PowerOnHours.Value.ToString(CultureInfo.InvariantCulture) + " hours" : "" });
                health.Add(new string[] { "Source", fallback != null ? fallback.Source + " (fallback)" : "none" });
                health.Add(new string[] { "Why fallback", r.CdiError });
            }

            healthCard.SetRows(health);

            // Format summary
            VolumeSummary v = r.Volume ?? new VolumeSummary();
            string outcome;
            if (!String.IsNullOrEmpty(r.Error) && !r.FormatAttempted)
            {
                outcome = "Error: " + r.Error;
            }
            else if (r.FormatAttempted && r.Format != null && r.Format.Success)
            {
                outcome = "Formatted ✓" + (r.Format.FallbackUsed ? " (exFAT fallback)" : "");
            }
            else if (r.FormatAttempted)
            {
                outcome = "FORMAT FAILED: " + FirstLine(r.Format != null ? r.Format.Output : r.Error);
            }
            else
            {
                outcome = r.SkipReason;
            }

            List<string[]> format = new List<string[]>();
            format.Add(new string[] { "Result", outcome, "b" });
            format.Add(new string[] { "File system", v.FileSystem });
            format.Add(new string[] { "Label", v.Ready && String.IsNullOrEmpty(v.Label) ? "(none)" : v.Label });
            format.Add(new string[] { "Drive letter", v.DriveLetter });
            format.Add(new string[] { "Capacity", v.Ready ? DiskService.FormatBytes(v.TotalBytes) : "" });
            format.Add(new string[] { "Available", v.Ready ? DiskService.FormatBytes(v.FreeBytes) + (v.TotalBytes > 0 ? "  (" + (100.0 * v.FreeBytes / v.TotalBytes).ToString("0.#", CultureInfo.InvariantCulture) + " %)" : "") : "" });
            format.Add(new string[] { "Partition style", disk.PartitionStyle });
            if (r.FormatAttempted)
            {
                format.Add(new string[] { "Finished", r.Finished.ToString("HH:mm:ss", CultureInfo.InvariantCulture) + "  (" + ((int)(r.Finished - r.Started).TotalSeconds).ToString(CultureInfo.InvariantCulture) + " s)" });
            }

            formatCard.SetRows(format);

            // Drive
            List<string[]> drive = new List<string[]>();
            drive.Add(new string[] { "Disk", "Disk " + disk.Number.ToString(CultureInfo.InvariantCulture) + " · " + disk.BusType });
            if (cdi != null)
            {
                drive.Add(new string[] { "Model", cdi.Field("Model") });
                drive.Add(new string[] { "Serial", cdi.Field("Serial Number") });
                drive.Add(new string[] { "Firmware", cdi.Field("Firmware") });
                drive.Add(new string[] { "Disk size", cdi.Field("Disk Size") });
                drive.Add(new string[] { "Interface", cdi.Field("Interface") });
                drive.Add(new string[] { "Transfer mode", cdi.Field("Transfer Mode") });
                AddIfPresent(drive, "Enclosure", cdi.Field("Enclosure"));
                AddIfPresent(drive, "Standard", FirstNonEmpty(cdi.Field("Standard"), cdi.Field("Major Version")));
                AddIfPresent(drive, "Rotation", cdi.Field("Rotation Rate"));
                drive.Add(new string[] { "Features", cdi.Field("Features") });
            }
            else
            {
                drive.Add(new string[] { "Model", disk.FriendlyName });
                drive.Add(new string[] { "Serial", disk.SerialNumber });
                drive.Add(new string[] { "Size", DiskService.FormatBytes(disk.Size) });
                drive.Add(new string[] { "Windows status", disk.HealthStatusText + " / " + disk.OperationalStatusText });
            }

            driveCard.SetRows(drive);

            // SMART table
            smartList.BeginUpdate();
            smartList.Items.Clear();
            if (cdi != null)
            {
                int row = 0;
                foreach (SmartAttribute a in cdi.Attributes)
                {
                    ListViewItem item = new ListViewItem(a.Id);
                    item.SubItems.Add(a.Name);
                    item.SubItems.Add(a.Current);
                    item.SubItems.Add(a.Worst);
                    item.SubItems.Add(a.Threshold);
                    item.SubItems.Add(a.RawHex);
                    item.SubItems.Add(a.RawDecimal.HasValue ? a.RawDecimal.Value.ToString("N0", CultureInfo.InvariantCulture) : "");
                    item.ForeColor = Palette.Text;
                    item.BackColor = a.Level == AttributeLevel.Bad ? Palette.RowBad : a.Level == AttributeLevel.Caution ? Palette.RowCaution : (row % 2 == 1 ? Palette.RowAlt : Palette.Card);
                    smartList.Items.Add(item);
                    row++;
                }

                bool nvme = cdi.IsNvme;
                smartList.Columns[2].Width = nvme ? 0 : 70;
                smartList.Columns[3].Width = nvme ? 0 : 70;
                smartList.Columns[4].Width = nvme ? 0 : 80;
                SetSmartNote(cdi.Attributes.Count == 0 ? "CrystalDiskInfo found this disk but it reported no S.M.A.R.T. attributes." : "");
            }
            else
            {
                List<string> notes = new List<string>();
                notes.Add(String.IsNullOrEmpty(r.CdiError) ? "No CrystalDiskInfo data for this disk." : r.CdiError);
                if (r.Fallback != null)
                {
                    notes.AddRange(r.Fallback.Notes);
                }

                SetSmartNote(String.Join("  ", notes.ToArray()));
            }

            smartList.EndUpdate();
            FitLastColumn();

            // Full report
            StringBuilder report = new StringBuilder();
            if (r.Report != null)
            {
                report.AppendLine(r.Report.Header);
                report.AppendLine();
                report.AppendLine(cdi != null ? cdi.RawSection : "(CrystalDiskInfo did not list this disk. Full report for all disks below.)\r\n\r\n" + r.Report.RawText);
            }
            else
            {
                report.AppendLine("CrystalDiskInfo report unavailable: " + r.CdiError);
                if (r.Fallback != null)
                {
                    report.AppendLine();
                    report.AppendLine("Fallback (" + r.Fallback.Source + "): " + r.Fallback.Overall);
                    foreach (string note in r.Fallback.Notes)
                    {
                        report.AppendLine("  " + note);
                    }
                }
            }

            if (r.FormatAttempted && r.Format != null && !String.IsNullOrEmpty(r.Format.Output))
            {
                report.AppendLine();
                report.AppendLine("-- DiskPart output ----------------------------------------------------------");
                report.AppendLine(r.Format.Output.Trim());
            }

            reportBox.Text = report.ToString();
        }

        private void LogResult(JobResult r)
        {
            string disk = "Disk " + r.Disk.Number.ToString(CultureInfo.InvariantCulture);
            if (r.FormatAttempted && r.Format != null)
            {
                AddLog(r.Format.Success
                    ? disk + " formatted as " + r.Format.FileSystem + (r.Format.FallbackUsed ? " (fallback)" : "") + ", " + r.Volume.DriveLetter + " \"" + r.Volume.Label + "\", " + DiskService.FormatBytes(r.Volume.FreeBytes) + " free."
                    : disk + " FORMAT FAILED: " + Collapse(r.Format.Output));
            }
            else if (!String.IsNullOrEmpty(r.SkipReason) && !r.Request.IsRescan)
            {
                AddLog(disk + ": " + r.SkipReason);
            }

            if (!String.IsNullOrEmpty(r.Error))
            {
                AddLog(disk + " error: " + r.Error);
            }

            AddLog(disk + " health: " + r.HealthStatus + (r.HealthPercent.HasValue ? " (" + r.HealthPercent.Value.ToString(CultureInfo.InvariantCulture) + " %)" : "") +
                (r.Cdi != null ? " via CrystalDiskInfo, " + r.Cdi.Attributes.Count.ToString(CultureInfo.InvariantCulture) + " attributes." : " via fallback. " + r.CdiError));
        }

