        private void SafeInvoke(MethodInvoker action)
        {
            try
            {
                if (IsDisposed || !IsHandleCreated)
                {
                    return;
                }

                BeginInvoke(action);
            }
            catch (ObjectDisposedException)
            {
            }
            catch (InvalidOperationException)
            {
            }
        }

        private void RelaunchButton_Click(object sender, EventArgs e)
        {
            try
            {
                ProcessStartInfo info = new ProcessStartInfo(Application.ExecutablePath);
                info.UseShellExecute = true;
                info.Verb = "runas";
                Process.Start(info);
                Close();
            }
            catch (Exception ex)
            {
                MessageBox.Show(ex.Message, "Could not relaunch", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private static List<DiskInfo> SortedDisks(IEnumerable<DiskInfo> disks)
        {
            List<DiskInfo> list = new List<DiskInfo>(disks);
            list.Sort(delegate(DiskInfo a, DiskInfo b) { return a.Number.CompareTo(b.Number); });
            return list;
        }

        private static void AddIfPresent(List<string[]> rows, string key, string value)
        {
            if (!String.IsNullOrEmpty(value))
            {
                rows.Add(new string[] { key, value });
            }
        }

        private static string FirstNonEmpty(string a, string b)
        {
            return String.IsNullOrEmpty(a) ? b : a;
        }

        private static string FirstLine(string text)
        {
            if (String.IsNullOrEmpty(text))
            {
                return "";
            }

            foreach (string line in text.Split('\n'))
            {
                string trimmed = line.Trim();
                if (trimmed.IndexOf("error", StringComparison.OrdinalIgnoreCase) >= 0 || trimmed.IndexOf("failed", StringComparison.OrdinalIgnoreCase) >= 0)
                {
                    return trimmed;
                }
            }

            return Collapse(text);
        }

        private static string Collapse(string text)
        {
            if (String.IsNullOrEmpty(text))
            {
                return "";
            }

            string collapsed = System.Text.RegularExpressions.Regex.Replace(text, "\\s+", " ").Trim();
            return collapsed.Length > 300 ? collapsed.Substring(0, 300) + "…" : collapsed;
        }

        private static bool IsAdministrator()
        {
            WindowsPrincipal principal = new WindowsPrincipal(WindowsIdentity.GetCurrent());
            return principal.IsInRole(WindowsBuiltInRole.Administrator);
        }
