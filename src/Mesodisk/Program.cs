        private void UpdateBanner()
        {
            if (bannerTitle == null)
            {
                return;
            }

            string queued = pending.Count > 0 ? "  ·  " + pending.Count.ToString(CultureInfo.InvariantCulture) + " more disk(s) queued" : "";
            string armedLine = armed
                ? "ARMED: the next new disk will be erased and formatted as " + SelectedFileSystem() + " \"" + DiskService.SanitizeVolumeLabel(labelBox.Text, SelectedFileSystem()) + "\". Auto-disarm in " + IdleCountdown() + "."
                : "DISARMED: new disks get a S.M.A.R.T. check only. " + (String.IsNullOrEmpty(disarmNote) || disarmNote == "Disarmed." ? "Press ARM to format." : disarmNote);

            bool showFormatNow = false;
            bool showRescan = false;

            if (!isAdmin)
            {
                SetBanner("Administrator rights required", "Mesodisk needs to run as Administrator to format disks and read S.M.A.R.T. data.", Palette.Red);
            }
            else if (busy && busyDisk != null)
            {
                SetBanner("Disk " + busyDisk.Number.ToString(CultureInfo.InvariantCulture) + "  ·  " + busyDisk.FriendlyName + "  ·  " + DiskService.FormatBytes(busyDisk.Size),
                    busyStep + queued, Palette.Blue);
            }
            else if (lastResult != null)
            {
                JobResult r = lastResult;
                string health = r.HealthStatus.ToUpperInvariant() + (r.HealthPercent.HasValue ? " " + r.HealthPercent.Value.ToString(CultureInfo.InvariantCulture) + "%" : "");
                string formatText = r.Formatted
                    ? "Formatted " + r.Format.FileSystem + " \"" + r.Volume.Label + "\"" + (String.IsNullOrEmpty(r.Volume.DriveLetter) ? "" : " (" + r.Volume.DriveLetter + ")")
                    : r.FormatAttempted ? "FORMAT FAILED" : "Not formatted";
                string title = "Disk " + r.Disk.Number.ToString(CultureInfo.InvariantCulture) + "  ·  " + health + "  ·  " + formatText;
                string detail = (lastResultRemoved ? "Disk removed. Results stay until the next disk.  " : "") + armedLine + queued;
                Color color = r.FormatAttempted && !r.Formatted ? Palette.Red : Palette.ForHealth(r.HealthStatus);
                SetBanner(title, detail, color);

                showRescan = !lastResultRemoved;
                if (!lastResultRemoved && !r.Formatted)
                {
                    DiskInfo disk = null;
                    lastPresent.TryGetValue(r.Disk.Number, out disk);
                    showFormatNow = disk != null && SafetyCheck(disk).Safe;
                }
            }
            else if (armed)
            {
                SetBanner("Insert a disk", armedLine + queued, Palette.Orange);
            }
            else
            {
                SetBanner("Ready", armedLine + "  The " + ProtectedCount().ToString(CultureInfo.InvariantCulture) + " disk(s) connected at launch are protected.", Palette.Grey);
            }

            formatNowButton.Visible = showFormatNow && !busy;
            rescanButton.Visible = showRescan && !busy;
            LayoutBannerButtons();
        }

