        private void SmartList_DrawColumnHeader(object sender, DrawListViewColumnHeaderEventArgs e)
        {
            using (SolidBrush background = new SolidBrush(Palette.Surface))
            {
                e.Graphics.FillRectangle(background, e.Bounds);
            }

            TextFormatFlags flags = TextFormatFlags.VerticalCenter | TextFormatFlags.EndEllipsis;
            flags |= e.Header.TextAlign == HorizontalAlignment.Right ? TextFormatFlags.Right : TextFormatFlags.Left;
            Rectangle bounds = new Rectangle(e.Bounds.X + 6, e.Bounds.Y, e.Bounds.Width - 12, e.Bounds.Height);
            TextRenderer.DrawText(e.Graphics, e.Header.Text, new Font("Segoe UI", 9f, FontStyle.Bold), bounds, Palette.Muted, flags);
        }

        private void FitLastColumn()
        {
            if (smartList.Columns.Count == 0)
            {
                return;
            }

            int used = 0;
            for (int i = 0; i < smartList.Columns.Count - 1; i++)
            {
                used += smartList.Columns[i].Width;
            }

            int remaining = smartList.ClientSize.Width - used - 2;
            smartList.Columns[smartList.Columns.Count - 1].Width = Math.Max(140, remaining);
        }

        // ------------------------------------------------------------------ Startup

        // Snapshot of every disk connected right now. These are protected for the whole session.
        private bool CaptureStartupDisks()
        {
            try
            {
                List<DiskInfo> disks = DiskService.EnumerateDisks();
                if (disks.Count == 0)
                {
                    return false; // there is always at least the system disk
                }

                startupSource = disks[0].Source;
                startupDiskCount = disks.Count;
                foreach (DiskInfo disk in disks)
                {
                    RememberStartupDisk(disk);
                    lastPresent[disk.Number] = disk;
                }

                // Also remember the identities the other Windows API reports, in case it is used later.
                try
                {
                    foreach (DiskInfo disk in DiskService.EnumerateWin32Disks())
                    {
                        RememberStartupDisk(disk);
                    }
                }
                catch
                {
                }

                startupCaptured = true;
                return true;
            }
            catch
            {
                return false;
            }
        }

        private void RememberStartupDisk(DiskInfo disk)
        {
            startupDiskKeys[DiskService.GetDiskKey(disk)] = true;
            if (!String.IsNullOrWhiteSpace(disk.SerialNumber))
            {
                startupSerials[disk.SerialNumber.Trim()] = true;
            }
        }

