        // ------------------------------------------------------------------ Detection

        private void PollDisks()
        {
            if (polling)
            {
                return;
            }

            polling = true;
            try
            {
                if (!startupCaptured)
                {
                    if (CaptureStartupDisks())
                    {
                        AddLog("Disk list read. " + ProtectedCount().ToString(CultureInfo.InvariantCulture) + " disk(s) connected now are protected.");
                        ApplyArmedState();
                    }

                    return;
                }

                List<DiskInfo> disks = DiskService.EnumerateDisks();
                if (disks.Count > 0 && !String.Equals(disks[0].Source, startupSource, StringComparison.Ordinal))
                {
                    // Disk IDs differ between the two Windows APIs; comparing them would make every disk look new.
                    if (!sourceMismatchLogged)
                    {
                        AddLog("Windows returned the disk list from a different API (" + disks[0].Source + " instead of " + startupSource + "). Detection paused until it recovers.");
                        sourceMismatchLogged = true;
                    }

                    return;
                }

                if (sourceMismatchLogged)
                {
                    AddLog("Disk list API recovered. Detection resumed.");
                    sourceMismatchLogged = false;
                }

                Dictionary<int, DiskInfo> current = new Dictionary<int, DiskInfo>();
                foreach (DiskInfo disk in disks)
                {
                    current[disk.Number] = disk;
                }

                foreach (KeyValuePair<int, DiskInfo> previous in lastPresent)
                {
                    if (!current.ContainsKey(previous.Key))
                    {
                        OnDiskRemoved(previous.Value);
                    }
                }

                foreach (DiskInfo disk in SortedDisks(disks))
                {
                    DiskInfo previous;
                    bool inserted;
                    if (!lastPresent.TryGetValue(disk.Number, out previous))
                    {
                        inserted = true;
                    }
                    else if (!String.Equals(DiskService.GetDiskKey(previous), DiskService.GetDiskKey(disk), StringComparison.OrdinalIgnoreCase))
                    {
                        // Identity changed at the same disk number: a swap, unless we just formatted it
                        // (Windows can report a new UniqueId after diskpart clean/convert).
                        inserted = !RecentlyFormatted(disk.Number);
                    }
                    else
                    {
                        inserted = previous.Size == 0 && disk.Size > 0; // media inserted into a reader
                    }

                    if (inserted && (disk.Number == activeNumber || InCooldown(disk.Number)))
                    {
                        inserted = false;
                    }

                    if (inserted && disk.Size > 0 && !pending.Contains(disk.Number))
                    {
                        pending.Add(disk.Number);
                        AddLog("New disk detected: Disk " + disk.Number.ToString(CultureInfo.InvariantCulture) + ", " + disk.FriendlyName + ", " + DiskService.FormatBytes(disk.Size) + ", " + disk.BusType + ".");
                    }
                }

                lastPresent = current;
                TryStartNext();
                UpdateFooter();
            }
            catch (Exception ex)
            {
                AddLog("Disk polling failed: " + ex.Message);
            }
            finally
            {
                polling = false;
            }
        }

        private bool RecentlyFormatted(int number)
        {
            DateTime until;
            return formattedUntil.TryGetValue(number, out until) && DateTime.Now < until;
        }

        private bool InCooldown(int number)
        {
            DateTime until;
            return cooldownUntil.TryGetValue(number, out until) && DateTime.Now < until;
        }

        private void OnDiskRemoved(DiskInfo disk)
        {
            formattedUntil.Remove(disk.Number);
            pending.Remove(disk.Number);
            if (disk.Number == activeNumber)
            {
                return; // the running job will report what happened
            }

            AddLog("Disk " + disk.Number.ToString(CultureInfo.InvariantCulture) + " removed (" + disk.FriendlyName + ").");
            if (lastResult != null && lastResult.Disk.Number == disk.Number && !lastResultRemoved)
            {
                lastResultRemoved = true;
                UpdateBanner();
            }
        }

        private void TryStartNext()
        {
            while (!busy && pending.Count > 0)
            {
                int number = pending[0];
                pending.RemoveAt(0);

                DiskInfo disk = null;
                try { disk = DiskService.FindDisk(number); } catch { }
                if (disk == null || disk.Size == 0)
                {
                    continue;
                }

                SafetyResult safety = SafetyCheck(disk);
                JobRequest request = NewRequest(disk);
                if (!safety.Safe)
                {
                    request.SkipReason = "Not formatted (blocked): " + String.Join(" ", safety.Messages.ToArray());
                }
                else if (!isAdmin)
                {
                    request.SkipReason = "Not formatted: Mesodisk is not running as Administrator.";
                }
                else if (!armed)
                {
                    request.SkipReason = "Not formatted: Mesodisk was disarmed. S.M.A.R.T. check only.";
                }
                else
                {
                    request.Format = true;
                }

                StartJob(request);
            }
        }

        private SafetyResult SafetyCheck(DiskInfo disk)
        {
            SafetyResult safety = DiskService.TestDiskSafeForFormat(disk, startupDiskKeys, startupSerials, usbOnlyCheck.Checked);
            if (!startupCaptured)
            {
                safety.Messages.Add("The startup disk list was never read.");
                safety.Safe = false;
            }
            else if (!String.Equals(disk.Source, startupSource, StringComparison.Ordinal))
            {
                safety.Messages.Add("Disk details came from a different Windows API than at startup.");
                safety.Safe = false;
            }

            return safety;
        }

        private JobRequest NewRequest(DiskInfo disk)
        {
            JobRequest request = new JobRequest();
            request.Disk = disk;
            request.FileSystem = SelectedFileSystem();
            request.PartitionStyle = DiskService.GetPartitionStyleForDisk(disk, Convert.ToString(partitionCombo.SelectedItem, CultureInfo.InvariantCulture));
            request.Label = DiskService.SanitizeVolumeLabel(labelBox.Text, request.FileSystem);
            request.Fallback = fallbackCheck.Checked;
            return request;
        }

        // ------------------------------------------------------------------ Jobs

        private void StartJob(JobRequest request)
        {
            busy = true;
            activeNumber = request.Disk.Number;
            busyDisk = request.Disk;
            lastActivity = DateTime.Now;
            busyStep = request.Format ? "Formatting as " + request.FileSystem + "…" : "Reading S.M.A.R.T. with CrystalDiskInfo…";

            if (!request.IsRescan)
            {
                lastResult = null;
                lastResultRemoved = false;
                ResetResultCards(request.Disk, request.Format ? "Formatting…" : request.SkipReason);
            }

            AddLog((request.IsRescan ? "Rescanning" : request.Format ? "Formatting" : "Checking") + " Disk " + request.Disk.Number.ToString(CultureInfo.InvariantCulture) + " (" + request.Disk.FriendlyName + ")" +
                (request.Format ? " as " + request.FileSystem + " \"" + request.Label + "\", " + request.PartitionStyle : "") + ".");

            UpdatePill();
            UpdateBanner();
            UpdateFooter();

            Thread worker = new Thread(RunJob);
            worker.IsBackground = true;
            worker.Start(request);
        }

        private void RunJob(object state)
        {
            JobRequest request = (JobRequest)state;
            JobResult result = new JobResult();
            result.Request = request;
            result.Disk = request.Disk;
            result.SkipReason = request.SkipReason;
            result.Started = DateTime.Now;
            int number = request.Disk.Number;

            try
            {
                if (request.Format)
                {
                    DiskInfo check = DiskService.FindDisk(number);
                    if (check == null || !String.Equals(DiskService.GetDiskKey(check), DiskService.GetDiskKey(request.Disk), StringComparison.OrdinalIgnoreCase))
                    {
                        throw new InvalidOperationException("Disk " + number.ToString(CultureInfo.InvariantCulture) + " changed or disappeared before formatting. Nothing was erased.");
                    }

                    result.FormatAttempted = true;
                    FormatResult format = DiskFormatter.FormatDisk(number, request.FileSystem, request.PartitionStyle, request.Label);
                    if (!format.Success && request.Fallback && String.Equals(request.FileSystem, "FAT32", StringComparison.OrdinalIgnoreCase))
                    {
                        Step("FAT32 failed (common above 32 GB). Formatting as exFAT…");
                        format = DiskFormatter.FormatDisk(number, "exFAT", request.PartitionStyle, request.Label);
                        format.FallbackUsed = format.Success;
                    }

                    result.Format = format;
                    if (format.Success)
                    {
                        Step("Waiting for the new volume to mount…");
                        result.Volume = DiskService.WaitForVolume(number, 25);
                    }
                }

                if (!result.Volume.Ready)
                {
                    result.Volume = DiskService.GetVolume(number);
                }

                result.After = DiskService.FindDisk(number) ?? request.Disk;

                Step("Reading S.M.A.R.T. with CrystalDiskInfo…");
                string message = "";
                string directory = isAdmin ? CdiRunner.ResolveDirectory(out message) : "";
                if (!isAdmin)
                {
                    message = "CrystalDiskInfo needs Administrator rights.";
                }

                result.CdiMessage = message;
                if (!String.IsNullOrEmpty(directory))
                {
                    string error;
                    result.Report = CdiRunner.Run(directory, CdiTimeoutSeconds, out error);
                    result.CdiError = error;
                    if (result.Report != null)
                    {
                        result.Cdi = result.Report.FindDisk(result.After, result.Volume.DriveLetter);
                        if (result.Cdi == null)
                        {
                            result.CdiError = "CrystalDiskInfo did not list this disk. Its USB bridge or card reader may not pass S.M.A.R.T. through.";
                        }
                    }
                }
                else
                {
                    result.CdiError = message;
                }

                if (result.Cdi == null)
                {
                    Step("Reading fallback health data…");
                    result.Fallback = HealthService.GetDiskHealth(result.After, smartCtlPath);
                }
            }
            catch (Exception ex)
            {
                result.Error = ex.Message;
            }

            result.Finished = DateTime.Now;
            SafeInvoke(delegate { JobFinished(result); });
        }

        private void Step(string text)
        {
            SafeInvoke(delegate
            {
                busyStep = text;
                UpdateBanner();
            });
        }

        private void JobFinished(JobResult result)
        {
            int number = result.Disk.Number;
            busy = false;
            activeNumber = -1;
            busyDisk = null;
            busyStep = "";
            lastActivity = DateTime.Now;
            cooldownUntil[number] = DateTime.Now.AddSeconds(5);

            if (result.FormatAttempted)
            {
                formattedUntil[number] = DateTime.Now.AddSeconds(30);
            }

            // Absorb any identity change caused by formatting so the same disk is not picked up again.
            DiskInfo now = null;
            try { now = DiskService.FindDisk(number); } catch { }
            if (now != null)
            {
                lastPresent[number] = now;
            }
            else
            {
                formattedUntil.Remove(number);
            }

            if (result.Request.IsRescan && lastResult != null)
            {
                result.FormatAttempted = lastResult.FormatAttempted;
                result.Format = lastResult.Format;
                result.SkipReason = lastResult.SkipReason;
                result.Started = lastResult.Started;
            }
            else
            {
                checkedCount++;
                if (result.Formatted)
                {
                    formattedCount++;
                }
            }

            lastResult = result;
            lastResultRemoved = now == null;
            LogResult(result);
            ShowResult(result);
            UpdatePill();
            UpdateBanner();
            UpdateFooter();
            TryStartNext();
        }

        private void FormatNowButton_Click(object sender, EventArgs e)
        {
            if (lastResult == null || busy)
            {
                return;
            }

            DiskInfo disk = DiskService.FindDisk(lastResult.Disk.Number);
            if (disk == null)
            {
                return;
            }

            DiskInfo shown = lastResult.After ?? lastResult.Disk;
            if (!String.Equals(DiskService.GetDiskKey(disk), DiskService.GetDiskKey(shown), StringComparison.OrdinalIgnoreCase))
            {
                MessageBox.Show("The disk at this number is no longer the one shown. Re-insert it to check it again.", "Formatting blocked", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            SafetyResult safety = SafetyCheck(disk);
            if (!safety.Safe)
            {
                MessageBox.Show(String.Join("\r\n", safety.Messages.ToArray()), "Formatting blocked", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            JobRequest request = NewRequest(disk);
            string message = "This will ERASE Disk " + disk.Number.ToString(CultureInfo.InvariantCulture) + ":\r\n\r\n" +
                "    " + disk.FriendlyName + "\r\n    " + DiskService.FormatBytes(disk.Size) + "    Serial: " + disk.SerialNumber + "\r\n\r\n" +
                "and format it as " + request.FileSystem + " \"" + request.Label + "\" (" + request.PartitionStyle + ").\r\n\r\nContinue?";
            if (MessageBox.Show(message, "Erase and format disk?", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes)
            {
                return;
            }

            if (busy)
            {
                MessageBox.Show("Mesodisk started working on another disk while this question was open. Try again when it finishes.", "Mesodisk", MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            request.Format = true;
            StartJob(request);
        }

