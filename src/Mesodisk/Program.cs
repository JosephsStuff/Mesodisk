    internal sealed class JobResult
    {
        public JobRequest Request;
        public DiskInfo Disk;
        public DiskInfo After;
        public bool FormatAttempted;
        public FormatResult Format;
        public string SkipReason = "";
        public VolumeSummary Volume = new VolumeSummary();
        public CdiReport Report;
        public CdiDisk Cdi;
        public string CdiMessage = "";
        public string CdiError = "";
        public HealthReport Fallback;
        public string Error = "";
        public DateTime Started;
        public DateTime Finished;

        public bool Formatted
        {
            get { return FormatAttempted && Format != null && Format.Success; }
        }

        public string HealthStatus
        {
            get
            {
                if (Cdi != null) return Cdi.HealthStatus;
                if (Fallback != null && Fallback.Passed.HasValue) return Fallback.Passed.Value ? "Good" : "Bad";
                return "Unknown";
            }
        }

        public int? HealthPercent
        {
            get
            {
                if (Cdi != null) return Cdi.HealthPercent;
                return Fallback != null ? Fallback.HealthPercent : null;
            }
        }
    }

    // A titled card of key/value rows for the left column.
    internal class InfoCard : Panel
    {
        private const int KeyWidth = 128;
        private readonly Label titleLabel;
        private readonly TableLayoutPanel table;
        protected readonly Panel extra;

        public InfoCard(string title)
        {
            BackColor = Palette.Card;
            Padding = new Padding(16, 12, 16, 12);
            Dock = DockStyle.Top;

            table = new TableLayoutPanel();
            table.Dock = DockStyle.Top;
            table.ColumnCount = 2;
            table.ColumnStyles.Add(new ColumnStyle(SizeType.Absolute, KeyWidth));
            table.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 100));
            table.AutoSize = true;
            table.AutoSizeMode = AutoSizeMode.GrowAndShrink;
            table.BackColor = Palette.Card;
            Controls.Add(table);

            extra = new Panel();
            extra.Dock = DockStyle.Top;
            extra.Height = 0;
            extra.BackColor = Palette.Card;
            Controls.Add(extra);

            titleLabel = new Label();
            titleLabel.Text = title.ToUpperInvariant();
            titleLabel.Font = new Font("Segoe UI", 8.5f, FontStyle.Bold);
            titleLabel.ForeColor = Palette.Muted;
            titleLabel.Dock = DockStyle.Top;
            titleLabel.Height = 24;
            Controls.Add(titleLabel);
        }

        private IList<string[]> lastRows;
        private int lastWidth;

        protected override void OnResize(EventArgs e)
        {
            base.OnResize(e);
            if (lastRows != null && Width != lastWidth)
            {
                SetRows(lastRows);
            }
        }

        public void SetRows(IList<string[]> rows)
        {
            lastRows = rows;
            lastWidth = Width;
            table.SuspendLayout();
            table.Controls.Clear();
            table.RowStyles.Clear();
            table.RowCount = Math.Max(rows.Count, 1);
            int valueWidth = Math.Max(120, Width - Padding.Horizontal - KeyWidth - 8);

            for (int i = 0; i < rows.Count; i++)
            {
                table.RowStyles.Add(new RowStyle(SizeType.AutoSize));

                Label key = new Label();
                key.Text = rows[i][0];
                key.ForeColor = Palette.Muted;
                key.Font = new Font("Segoe UI", 9f);
                key.AutoSize = true;
                key.Margin = new Padding(0, 3, 6, 3);
                table.Controls.Add(key, 0, i);

                Label value = new Label();
                value.Text = String.IsNullOrEmpty(rows[i][1]) ? "—" : rows[i][1];
                value.ForeColor = Palette.Text;
                value.Font = new Font("Segoe UI", 9.5f, rows.Count > 0 && rows[i].Length > 2 && rows[i][2] == "b" ? FontStyle.Bold : FontStyle.Regular);
                value.AutoSize = true;
                value.MaximumSize = new Size(valueWidth, 0);
                value.Margin = new Padding(0, 3, 0, 3);
                table.Controls.Add(value, 1, i);
            }

            table.ResumeLayout(true);
            Height = Padding.Vertical + 24 + extra.Height + table.GetPreferredSize(new Size(Width - Padding.Horizontal, 0)).Height;
        }
    }

