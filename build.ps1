<#
.SYNOPSIS
  Builds Mesodisk.exe as a single portable file with CrystalDiskInfo embedded.

.DESCRIPTION
  Uses the C# compiler that ships with Windows (.NET Framework 4.x), so no SDK or
  Visual Studio is needed. Used by Build-Mesodisk.cmd (double-click) and by the
  GitHub Actions release workflow.

  Output:
    bin\Mesodisk\                         the app folder (exe + notices)
    dist\Mesodisk.exe                     the portable exe on its own
    dist\Mesodisk-<version>-Windows-x64.zip
    dist\SHA256SUMS.txt

.PARAMETER Version
  Version to stamp, e.g. 1.2.0 or v1.2.0. Defaults to the git tag (git describe),
  or 0.0.0-dev when there is no tag.
#>
[CmdletBinding()]
param(
    [string]$Version = ""
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version 2.0

$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$Src  = Join-Path $Root "src\Mesodisk"
$Cdi  = Join-Path $Root "third_party\CrystalDiskInfo"
$Obj  = Join-Path $Root "obj"
$Out  = Join-Path $Root "bin\Mesodisk"
$Dist = Join-Path $Root "dist"
$Fw   = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319"
$Csc  = Join-Path $Fw "csc.exe"

Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem

function Write-Step([string]$Text) { Write-Host "==> $Text" -ForegroundColor Cyan }

# Zip a folder with forward-slash entry names (Windows PowerShell 5.1 otherwise writes backslashes).
function New-Zip([string]$SourceDir, [string]$ZipPath, [string]$Prefix, [string[]]$Exclude) {
    if (Test-Path $ZipPath) { Remove-Item $ZipPath -Force }
    $base = (Resolve-Path $SourceDir).Path.TrimEnd('\') + '\'
    $zip = [System.IO.Compression.ZipFile]::Open($ZipPath, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
        Get-ChildItem -Path $SourceDir -Recurse -File | ForEach-Object {
            $relative = $_.FullName.Substring($base.Length)
            foreach ($pattern in $Exclude) { if ($relative -like $pattern) { return } }
            $entry = ($Prefix + $relative) -replace '\\', '/'
            [void][System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $_.FullName, $entry, [System.IO.Compression.CompressionLevel]::Optimal)
        }
    }
    finally {
        $zip.Dispose()
    }
}

# ---------------------------------------------------------------- version
if (-not $Version) {
    if ($env:GITHUB_REF_TYPE -eq "tag" -and $env:GITHUB_REF_NAME) {
        $Version = $env:GITHUB_REF_NAME
    }
    else {
        try { $Version = (& git -C $Root describe --tags --match "v*" 2>$null) } catch { $Version = "" }
        if (-not $Version) {
            $sha = ""
            try { $sha = (& git -C $Root rev-parse --short HEAD 2>$null) } catch { }
            $Version = "0.0.0-dev" + $(if ($sha) { "+$sha" } else { "" })
        }
    }
}

$Version = "$Version".Trim().TrimStart('v', 'V')
if ($Version -notmatch '^(\d+)\.(\d+)\.(\d+)') {
    throw "Version '$Version' must start with MAJOR.MINOR.PATCH, e.g. 1.2.0"
}
$NumericVersion = "$($Matches[1]).$($Matches[2]).$($Matches[3]).0"
Write-Step "Building Mesodisk $Version ($NumericVersion)"

# ---------------------------------------------------------------- checks
if (-not (Test-Path $Csc)) { throw "C# compiler not found at $Csc (.NET Framework 4.x is part of Windows 10/11)." }
if (-not (Test-Path (Join-Path $Cdi "DiskInfo64.exe"))) { throw "CrystalDiskInfo not found in $Cdi" }

foreach ($dir in @($Obj, $Dist)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
if (Test-Path $Out) { Remove-Item $Out -Recurse -Force }
New-Item -ItemType Directory -Force -Path $Out | Out-Null
Get-ChildItem $Dist -File -ErrorAction SilentlyContinue | Remove-Item -Force

# ---------------------------------------------------------------- generated version info
$versionFile = Join-Path $Obj "VersionInfo.cs"
@"
// Generated by build.ps1 - do not edit.
using System.Reflection;
[assembly: AssemblyVersion("$NumericVersion")]
[assembly: AssemblyFileVersion("$NumericVersion")]
[assembly: AssemblyInformationalVersion("$Version")]
"@ | Set-Content -Path $versionFile -Encoding UTF8

# ---------------------------------------------------------------- embed CrystalDiskInfo
Write-Step "Packing CrystalDiskInfo"
$cdiZip = Join-Path $Obj "CrystalDiskInfo.zip"
New-Zip -SourceDir $Cdi -ZipPath $cdiZip -Prefix "" -Exclude @("DiskInfo.txt", "Smart\*", "*.md")

# ---------------------------------------------------------------- compile
Write-Step "Compiling"
$exe = Join-Path $Out "Mesodisk.exe"
$cscArgs = @(
    "/nologo", "/target:winexe", "/platform:x64", "/optimize+", "/codepage:65001", "/warn:4",
    "/win32manifest:$(Join-Path $Src 'app.manifest')",
    "/out:$exe",
    "/resource:$cdiZip,Mesodisk.CrystalDiskInfo.zip",
    "/reference:System.dll",
    "/reference:System.Core.dll",
    "/reference:System.Drawing.dll",
    "/reference:System.Management.dll",
    "/reference:System.Web.Extensions.dll",
    "/reference:System.Windows.Forms.dll",
    "/reference:$(Join-Path $Fw 'System.IO.Compression.dll')",
    (Join-Path $Src "Program.cs"),
    (Join-Path $Src "DiskCore.cs"),
    (Join-Path $Src "CrystalDiskInfo.cs"),
    $versionFile
)
& $Csc @cscArgs
if ($LASTEXITCODE -ne 0) { throw "Compilation failed (csc exit code $LASTEXITCODE)." }

# ---------------------------------------------------------------- package
Write-Step "Packaging"
foreach ($file in @("README.md", "LICENSE", "NOTICE.txt", "THIRD_PARTY_NOTICES.txt")) {
    $path = Join-Path $Root $file
    if (Test-Path $path) { Copy-Item $path $Out }
}
$licenses = Join-Path $Out "licenses\CrystalDiskInfo"
New-Item -ItemType Directory -Force -Path $licenses | Out-Null
Copy-Item (Join-Path $Cdi "License\*") $licenses

$zipName = "Mesodisk-$Version-Windows-x64.zip" -replace '\+', '-'
New-Zip -SourceDir $Out -ZipPath (Join-Path $Dist $zipName) -Prefix "Mesodisk\" -Exclude @()
Copy-Item $exe (Join-Path $Dist "Mesodisk.exe")

$sums = Get-ChildItem $Dist -File | Where-Object { $_.Name -ne "SHA256SUMS.txt" } | Sort-Object Name | ForEach-Object {
    (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant() + "  " + $_.Name
}
$sums | Set-Content (Join-Path $Dist "SHA256SUMS.txt") -Encoding ASCII

# Release notes used by the GitHub workflow (UTF-8 without BOM).
$exeSize = "{0:N1} MB" -f ((Get-Item $exe).Length / 1MB)
$cdiVersion = (Get-Item (Join-Path $Cdi "DiskInfo64.exe")).VersionInfo.ProductVersion
$notes = @"
## Mesodisk $Version

**Download ``Mesodisk.exe``** ($exeSize) - a single portable file. No install: run it and accept the Administrator prompt.
``$zipName`` contains the same exe plus the README and licence notices.

Includes CrystalDiskInfo $cdiVersion (MIT, (C) hiyohiyo).

### SHA-256
``````
$($sums -join "`n")
``````

> Windows SmartScreen may warn that the publisher is unknown because the exe is not code-signed. Choose **More info > Run anyway**.
"@
[System.IO.File]::WriteAllText((Join-Path $Obj "release-notes.md"), $notes, (New-Object System.Text.UTF8Encoding($false)))

Write-Host ""
Write-Host "Built Mesodisk $Version" -ForegroundColor Green
Get-ChildItem $Dist -File | ForEach-Object { Write-Host ("  dist\" + $_.Name) }
